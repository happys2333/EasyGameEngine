package org.happys.engine.model;

public class EGVector {
    private float x;

    private float y;

    private float z;

    public EGVector(float x, float y, float z) {
        this.x = x;
        this.y = y;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }

    public float getZ() {
        return z;
    }
}
